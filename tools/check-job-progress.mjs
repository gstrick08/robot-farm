import assert from 'node:assert/strict';
import { readProgress, writeProgress, validJobs, JOB_KEY } from '../job-progress.js';
import * as L from '../logic.js';
import {readFileSync} from 'node:fs';
const data = new Map(), storage = {getItem:k=>data.get(k)||null,setItem:(k,v)=>data.set(k,v)};
const key='robotfarm.v1', original=JSON.parse(readFileSync(new URL('fixtures/played-v1.json',import.meta.url))), state=structuredClone(original);
const m=L.createMission(Array(17).fill('W:like'));L.nextTarget(m);
const job={context:'context',n:0,job:0,type:'hunt',phase:'question',m,ease:false,paidGold:0,question:{options:['W:like','W:look'],wrong:[],hint:false,font:'Andika',teach:false}};
storage.setItem(key,JSON.stringify(original));
assert.equal(validJobs([job]),true);
writeProgress(storage,key,state,[job]);
assert.deepEqual(readProgress(storage,key),{raw:JSON.stringify(state),jobs:[job]});
L.answer(m,false);job.question.wrong=['W:look'];job.question.hint=true;
writeProgress(storage,key,state,[job]);
assert.deepEqual(readProgress(storage,key).jobs[0].m,m,'firstTry, repeat queue and question count survive reload');
assert.deepEqual(readProgress(storage,key).jobs[0].question,job.question,'faded choices and hint survive reload');
L.answer(m,true);job.phase='advance';state.seeds++;job.paidGold=m.golds;
// Fail exactly between the two writes, then recover the paired state and checkpoint.
const before=storage.getItem(key);
assert.throws(()=>writeProgress({...storage,setItem(k,v){if(k===key)throw Error('interrupted');storage.setItem(k,v);}},key,state,[job]));
assert.equal(storage.getItem(key),before);
assert.deepEqual(JSON.parse(readProgress(storage,key).raw),state);
assert.equal(readProgress(storage,key).jobs[0].phase,'advance','answered question is never offered again');
const loaded=readProgress(storage,key).jobs[0];
assert.equal(m.golds-loaded.paidGold,0,'quitting an already-paid checkpoint adds no duplicate seeds');
writeProgress(storage,key,state,[]);assert.deepEqual(readProgress(storage,key).jobs,[],'finished job cleared');
writeProgress(storage,key,state,[job]);storage.setItem(key,JSON.stringify({...original,seeds:99}));
assert.equal(JSON.parse(readProgress(storage,key).raw).seeds,99,'external backup restore is never overwritten by a stale checkpoint');
assert.deepEqual(readProgress(storage,key).jobs,[]);
const protectedRaw=storage.getItem(key);storage.setItem(JOB_KEY,JSON.stringify({v:1,before:protectedRaw,after:'{"v":1}',jobs:[job]}));assert.equal(readProgress(storage,key).raw,protectedRaw,'incomplete transaction cannot replace a full learning save');
storage.setItem(JOB_KEY,'{broken');assert.equal(JSON.parse(readProgress(storage,key).raw).seeds,99,'corrupted sidecar cannot erase progress');
for(const bad of [{...job,paidGold:99},{...job,m:{...m,asked:99}},{...job,question:{...job.question,options:['W:look']}},{...job,phase:'oops'}])assert.equal(validJobs([bad]),false);
console.log('Job checkpoint, interrupted-write recovery and reward checks passed ✔');
